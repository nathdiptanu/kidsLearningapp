PlaceRecord _place({
  required String id,
  required String name,
  required String hindiName,
  required AdminType adminType,
  required String fact,
  required String page,
  List<CapitalSeat> capitals = const [],
  bool smallTarget = false,
}) {
  return PlaceRecord(
    id: id,
    name: name,
    hindiName: hindiName,
    adminType: adminType,
    geometryId: id,
    fact: SourcedFact(
      id: 'fact-$id',
      text: fact,
      sourceName: 'Know India, National Portal of India',
      sourceUrl: page,
      verifiedAt: _verifiedOn,
      reviewStatus: ReviewStatus.placeholder,
    ),
    capitals: capitals,
    reviewStatus: ReviewStatus.placeholder,
    rightsStatus: 'development_only',
    sources: [page, _directory],
    narrationId: 'clip_geo_${id.substring(3).replaceAll('-', '_')}',
    smallTarget: smallTarget,
  );
}

CapitalSeat _capital(String name, String hindi, String page) {
  return CapitalSeat(
    name: name,
    hindiName: hindi,
    role: CapitalRole.sole,
    sourceName: 'Know India, National Portal of India',
    sourceUrl: page,
    verifiedAt: _verifiedOn,
    reviewStatus: ReviewStatus.placeholder,
  );
}

